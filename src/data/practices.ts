/**
 * practices.ts — the content library. This is the product.
 *
 * Editorial rules, because the writing is the thing people actually feel:
 *
 *   TITLES are short and concrete. "Unclench" beats "Relaxation Session 3".
 *   A title should name the experience, not the category.
 *
 *   SUBTITLES say who this is for, in their words, at the moment they need it —
 *   "for the jaw you didn't know you were holding". Never mystical, never
 *   clinical, never a slogan.
 *
 *   SCRIPTS are `[secondsFromStart, line]`. Second person, present tense, kind.
 *   One line every 15-45 seconds and no more: the silence between lines is the
 *   practice, and a script that fills every second is a podcast. Lines are short
 *   enough to be heard once and understood. Never promise a feeling.
 *
 *   TAGS come from `PRACTICE_TAGS` below and nothing else. The agent's
 *   `recommend_practice` tool filters on them, so a typo is a missing practice.
 *   `short` means 5 minutes or under. `beginner` means you could hand it to
 *   someone who has never done this and they would not feel stupid.
 *
 * Nothing here treats, diagnoses or promises anything — see `safety.ts`.
 */

